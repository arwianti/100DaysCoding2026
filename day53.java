public class BreakSederhana {
    public static void main(String[] args) {
        
        
       for (int i = 1; i <= 5; i++) {
            
            
        if (i == 3) {
               break; 
            }
         System.out.println("Angka: " + i);
        }
        System.out.println("Perulangan berhenti di angka 3");
    }
}
