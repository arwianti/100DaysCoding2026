public class Percabangan {
    public static void main(String[] args) {

        int nilai = 80;

        if (nilai >= 85) {
            System.out.println("Nilai A");
        } else if (nilai >= 70) {
            System.out.println("Nilai B");
        } else if (nilai >= 60) {
            System.out.println("Nilai C");
        } else {
            System.out.println("Nilai D");
        }
    }
}
